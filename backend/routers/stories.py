@router.post("/stories/projects", status_code=201)
async def create_story_project(
    payload: CreateStoryProjectRequest, user_id: str = Depends(get_current_user_id)
):
    """Create a story draft against an APPROVED App Profile.

    The row is an ordinary studio project with kind='story' (ADR 0227):
    same table, same PATCH, same reads — only the create path and the
    plan/generate/kit endpoints are story-shaped. The type is validated
    against the settled catalog loudly, and the frame length is the
    type's default or the founder's pick from the settled 5/10/15 set.
    hook_seconds is 2, the shared machinery's floor: the story's
    first-second rule lives in the plan prompt and the craft check, and
    the row only needs a value inside the range the shared repairs
    accept so nothing rewrites the frame's shape on read.
    """
    profile = await _require_profile_for_studio(payload.brand_profile_id, user_id)

    story_type = story_types.get_story_type(payload.story_type)
    if story_type is None:
        raise HTTPException(
            status_code=400,
            detail=(
                f"Unknown story type {payload.story_type!r}: pick one of "
                + ", ".join(story_types.STORY_TYPE_IDS) + "."
            ),
        )
    seconds = payload.frame_seconds or story_type["default_seconds"]
    if seconds not in story_types.STORY_FRAME_SECONDS:
        raise HTTPException(
            status_code=400,
            detail="A story frame runs 5, 10, or 15 seconds.",
        )

    project_id = str(uuid.uuid4())
    now = now_iso()
    await _execute(
        """INSERT INTO studio_projects
           (id, brand_profile_id, content_angle_id, template_id, template_version,
             objective, audience, duration_seconds, hook_seconds, extend_intent, tone, assets,
             script_version, status, created_at, updated_at, user_id, camera_setup, kind,
             story_type, frame_count)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
        (project_id, profile["id"], (payload.content_angle_id or "").strip() or None,
         None, None, None,
         (profile.get("target_audience") or "").strip() or None,
         seconds, 2, 1, None,
         json.dumps([]), 0, "draft", now, now, user_id, payload.camera_setup,
         "story", story_type["id"], 1),
    )
    logger.info(f"Created story project {project_id} for profile {profile['id']}")
    return _public_project(
        await _fetch_one("SELECT * FROM studio_projects WHERE id = ?", (project_id,)),
        brand_name=(profile.get("brand_name") or "").strip(),
    )


async def _story_project_row(project_id: str, user_id: str) -> dict:
    """The story row for a story endpoint: 404 when missing, 400 when
    the row is a hook video — a story endpoint answering a video project
    with story copy would be a silent kind mix-up."""
    row = await _fetch_one(
        "SELECT * FROM studio_projects WHERE id = ? AND user_id = ?",
        (project_id, user_id),
    )
    if not row:
        raise HTTPException(status_code=404, detail="Story project not found")
    if (row.get("kind") or "video") != "story":
        raise HTTPException(
            status_code=400,
            detail="This project is not a story — it is a hook video project.",
        )
    return row


@router.post("/stories/projects/{project_id}/plan")
async def generate_story_plan(
    project_id: str, payload: GenerateStoryPlanRequest,
    user_id: str = Depends(get_current_user_id),
):
    """
    Write the frame's plan: spoken lines, screen text, sticker plan.

    One generation, saved as the project's written layer plus the
    strategy the render reads (ADR 0228): the strategy is assembled
    here, deterministically, from the plan's own beats and the saved
    direction picks — a story has no separate strategy step, because
    its review surface is the plan itself. The scene is locked from the
    direction the founder saved (ADR 0220's rule: camera and location
    are chosen before the plan, and the plan respects them); only an
    untouched draft takes the plan's own location.
    """
    require_ai_configured()
    row = await _story_project_row(project_id, user_id)
    profile = await _require_profile_for_studio(row.get("brand_profile_id"), user_id)
    _refuse_retired_project_assets(row.get("assets"))

    story_type = story_types.get_story_type(
        payload.story_type or row.get("story_type")
    )
    if story_type is None:
        raise HTTPException(
            status_code=400,
            detail=(
                f"Unknown story type {payload.story_type or row.get('story_type')!r}: "
                "pick one of " + ", ".join(story_types.STORY_TYPE_IDS) + "."
            ),
        )
    seconds = payload.frame_seconds or int(row.get("duration_seconds") or 0)
    if seconds not in story_types.STORY_FRAME_SECONDS:
        seconds = story_type["default_seconds"]

    angle = None
    if row.get("content_angle_id"):
        angle = await _fetch_one(
            "SELECT * FROM content_angles WHERE id = ? AND brand_profile_id = ? AND user_id = ?",
            (row["content_angle_id"], row.get("brand_profile_id"), user_id),
        )
        if not angle:
            raise HTTPException(
                status_code=404, detail="Content angle not found for this App Profile"
            )

    plan_project = dict(row)
    plan_project["story_type"] = story_type["id"]
    plan_project["duration_seconds"] = seconds
    plan_project["content_angle"] = angle
    plan_project["countdown_date"] = (payload.countdown_date or "").strip()
    try:
        plan = await _log_model_call(
            "story_plan", "text", TEXT_MODEL,
            lambda: ai_service.generate_story_plan(plan_project, profile),
            user_id,
            brand_profile_id=row.get("brand_profile_id"),
            studio_project_id=project_id,
        )
    except Exception as e:
        raise HTTPException(status_code=502, detail=f"Story plan failed: {str(e)[:800]}")

    location = (row.get("location") or "").strip() or plan.get("location") or ""
    strategy = {
        "hook_concept": plan.get("hook_line") or "",
        "hook_promise": "",
        "strategy_summary": "",
        "audience_problem": (angle or {}).get("problem") or "",
        "segments": [
            {
                "index": 0, "role": "hook", "seconds": 1,
                "goal": "Open on the moment",
                "script": plan.get("hook_line") or "",
                "action": plan.get("hook_action") or "",
            },
            {
                "index": 1, "role": "middle", "seconds": max(1, seconds - 1),
                "goal": "The frame's one idea",
                "script": plan.get("script") or "",
                "action": plan.get("middle_action") or "",
            },
        ],
        "scene": {
            "location": location,
            "camera_angle": "", "framing": "", "lighting": "",
            "visual_style": "", "character_positioning": "",
            "wardrobe": (row.get("visual_direction") or "").strip(),
            "props": "", "color_palette": "",
        },
        "camera_setup": row.get("camera_setup") or "handheld",
        "story_brief": {
            "story_type": story_type["id"],
            "story_type_name": story_type["name"],
            "frame_seconds": seconds,
            "screen_text": plan.get("screen_text") or "",
        },
    }
    await _execute(
        "UPDATE studio_projects SET hook_line = ?, script = ?, "
        "screen_text = ?, sticker_plan = ?, story_type = ?, "
        "duration_seconds = ?, location = ?, strategy = ?, "
        "script_version = script_version + 1, updated_at = ? "
        "WHERE id = ? AND user_id = ?",
        (
            plan.get("hook_line") or "", plan.get("script") or "",
            plan.get("screen_text") or "",
            json.dumps(plan.get("sticker_plan") or []),
            story_type["id"], seconds, location or None,
            json.dumps(strategy), now_iso(), project_id, user_id,
        ),
    )
    return _public_project(
        await _fetch_one("SELECT * FROM studio_projects WHERE id = ?", (project_id,)),
        brand_name=(profile.get("brand_name") or "").strip(),
    )


@router.post("/stories/projects/{project_id}/screen-text-suggestion")
async def suggest_story_screen_text(
    project_id: str, payload: SuggestStoryScreenTextRequest,
    user_id: str = Depends(get_current_user_id),
):
    """
    One fresh screen text the founder may accept (ADR 0236).

    Advisory like the cover text's suggestion (ADR 0145): writes
    nothing, and accepting goes through the page's normal draft edit.
    The suggestion is written from the editor's current values — the
    payload's lines win, the saved row fills what the payload omits —
    under the plan's own screen-text rules, so it obeys the same caps
    and the same sound-off doctrine as the text it would replace. A
    refusal surfaces with its reason, in the founder's words (the
    studio rewrite endpoints' rule).
    """
    require_ai_configured()
    row = await _story_project_row(project_id, user_id)
    profile = await _require_profile_for_studio(row.get("brand_profile_id"), user_id)

    suggestion_project = dict(row)
    if payload.hook_line is not None:
        suggestion_project["hook_line"] = payload.hook_line
    if payload.script is not None:
        suggestion_project["script"] = payload.script
    if payload.screen_text is not None:
        suggestion_project["screen_text"] = payload.screen_text
    if row.get("content_angle_id"):
        angle = await _fetch_one(
            "SELECT * FROM content_angles WHERE id = ? AND brand_profile_id = ? AND user_id = ?",
            (row["content_angle_id"], row.get("brand_profile_id"), user_id),
        )
        suggestion_project["content_angle"] = angle
    try:
        text = await _log_model_call(
            "story_screen_text", "text", TEXT_MODEL,
            lambda: ai_service.suggest_story_screen_text(suggestion_project, profile),
            user_id,
            brand_profile_id=row.get("brand_profile_id"),
            studio_project_id=project_id,
        )
    except ai_service.RewriteRefusal as e:
        raise HTTPException(status_code=422, detail=str(e))
    except Exception as e:
        logger.error(f"Story screen text suggestion failed: {type(e).__name__}: {e}")
        raise HTTPException(
            status_code=502, detail=f"Screen text suggestion failed: {str(e)[:800]}")
    return {
        "screen_text": text,
        "original": " ".join(str(suggestion_project.get("screen_text") or "").split()).strip(),
    }


@router.post("/stories/projects/{project_id}/generate", status_code=202)
async def generate_story(
    project_id: str, payload: GenerateStoryRequest,
    user_id: str = Depends(get_current_user_id),
    request: Request = None,
):
    """
    Render ONE story frame as ONE job, through the only render path.

    A story has no ready-marking gate: its readiness is the plan
    itself — no plan, no render — plus the same model, resolution and
    single-pass checks every submit makes. The frame submits at its
    own seconds (exact_duration: the hook-video clamp floors at 8 and
    would silently rewrite a 5-second frame), with the stored strategy
    rebound to the project's current words, so an edit made after the
    plan is what renders.
    """
    require_ai_configured()
    row = await _story_project_row(project_id, user_id)
    profile = await _require_profile_for_studio(row.get("brand_profile_id"), user_id)
    _refuse_retired_project_assets(row.get("assets"))

    if not (row.get("hook_line") or "").strip() or not (row.get("script") or "").strip():
        raise HTTPException(
            status_code=409,
            detail="Generate the story plan first — a frame renders its plan's words.",
        )

    _assert_model_usable(payload.model or "")
    _assert_resolution_offered(payload.model or "", payload.resolution)

    seconds = int(payload.duration_seconds or row.get("duration_seconds") or 0)
    if seconds not in story_types.STORY_FRAME_SECONDS:
        raise HTTPException(
            status_code=400,
            detail="A story frame runs 5, 10, or 15 seconds.",
        )
    _assert_within_single_pass_cap(
        video_providers.resolve(payload.model or None)[0], seconds)

    strategy = _project_strategy(row)
    if strategy:
        # Rebind the current words, the same discipline the wizard's
        # render applies: the strategy's sections carry the plan's
        # lines, and a founder edit since must be what the render says.
        segments = [dict(s) for s in (strategy.get("segments") or [])]
        for segment in segments:
            if segment.get("role") == "hook":
                segment["script"] = row.get("hook_line") or ""
            elif segment.get("role") == "middle":
                segment["script"] = row.get("script") or ""
        strategy = {**strategy, "segments": segments}
        scene = dict(strategy.get("scene") or {})
        if (row.get("location") or "").strip():
            scene["location"] = (row.get("location") or "").strip()
        strategy = {**strategy, "scene": scene}

    project = dict(row)
    project["duration_seconds"] = seconds
    generation = await _submit_generation(
        project=project,
        profile=profile,
        template={},
        user_id=user_id,
        model=payload.model or "",
        duration=seconds,
        segment_index=payload.segment_index,
        generate_audio=payload.generate_audio,
        resolution=payload.resolution,
        strategy=strategy or None,
        exact_duration=True,
        idempotency_key=payload.idempotency_key or "",
        request_id=(request.state.request_id if request is not None and getattr(request, "state", None) else "") or _request_id(),
    )
    generation["provider_reason"] = video_providers.resolve(payload.model or None)[1]
    return generation
