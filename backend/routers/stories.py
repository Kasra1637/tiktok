# ---------------------------------------------------------------------------
# The story kit: the post kit's sibling (ADR 0228)
# ---------------------------------------------------------------------------

def _parse_story_kit(value) -> Optional[dict]:
    """The frozen story kit for a generation, or None when never written."""
    if isinstance(value, dict):
        return value
    if isinstance(value, str) and value.strip():
        try:
            parsed = json.loads(value)
        except (json.JSONDecodeError, TypeError, ValueError):
            return None
        return parsed if isinstance(parsed, dict) else None
    return None


async def _schedule_story_kit(
    background_tasks: BackgroundTasks, generation_id: str, user_id: str
) -> None:
    """Kit work runs after the response, never inside it.

    On HTTP the work is deferred to BackgroundTasks; direct (non-HTTP)
    callers such as tests pass None and run it inline. Same contract as
    _schedule_post_kit.
    """
    if background_tasks is not None:
        background_tasks.add_task(_maybe_write_story_kit, generation_id, user_id)
        return
    await _maybe_write_story_kit(generation_id, user_id)


async def _load_story_kit_materials(generation_row: dict, user_id: str):
    """The render material a story kit is grounded in, or (None, None).

    The post kit loader's twin, with the story's own columns: the kit
    needs the accepted screen text and the sticker plan, which the post
    kit never reads. A render whose project is not a story has no story
    kit material at all — the two kits are mutually exclusive by kind.
    """
    project = None
    if generation_row.get("studio_project_id"):
        project = await _fetch_one(
            "SELECT hook_line, script, story_type, screen_text, sticker_plan, "
            "duration_seconds, kind FROM studio_projects "
            "WHERE id = ? AND user_id = ?",
            (generation_row["studio_project_id"], user_id),
        )
    if not project or (project.get("kind") or "video") != "story":
        return None, None
    profile = None
    if generation_row.get("brand_profile_id"):
        profile = await _fetch_one(
            "SELECT * FROM brand_profiles WHERE id = ? AND user_id = ?",
            (generation_row["brand_profile_id"], user_id),
        )
    return project, profile


async def _maybe_write_story_kit(generation_id: str, user_id: str) -> Optional[dict]:
    """Write the frozen story kit for a freshly completed render, once.

    Best-effort by design, like the post kit's writer: a kit failure
    logs loudly and leaves the column NULL rather than failing the
    completion or inventing copy. A hook-video completion finds no
    story material and returns quietly.
    """
    current = await _fetch_one(
        "SELECT story_kit, studio_project_id, brand_profile_id FROM generations WHERE id = ?",
        (generation_id,),
    )
    if not current:
        return None
    if _parse_story_kit(current.get("story_kit")) is not None:
        return None
    project, profile = await _load_story_kit_materials(current, user_id)
    if not project or not profile:
        return None
    try:
        kit = await _log_model_call(
            "story_kit", "text", TEXT_MODEL,
            lambda: ai_service.generate_story_kit(project, profile, current),
            user_id,
            brand_profile_id=current.get("brand_profile_id"),
            studio_project_id=current.get("studio_project_id"),
            generation_id=generation_id,
        )
    except Exception as e:
        logger.warning("Story kit generation failed for %s: %s", generation_id, e)
        return None
    if not isinstance(kit, dict):
        logger.warning("Story kit generation returned no kit for %s.", generation_id)
        return None
    await _execute(
        "UPDATE generations SET story_kit = ?, updated_at = ? "
        "WHERE id = ? AND (story_kit IS NULL OR story_kit = '')",
        (json.dumps(kit), now_iso(), generation_id),
    )
    return kit


@router.post("/generations/{generation_id}/story-kit/regenerate")
async def regenerate_story_kit(
    generation_id: str, user_id: str = Depends(get_current_user_id)
):
    """Write a fresh story kit for a render and replace the saved one.

    Click-only by construction: nothing else calls generate_story_kit
    for a replacement. A failure answers loudly and leaves the stored
    kit untouched. A hook-video render is refused — it has a post kit,
    and the two never mix (ADR 0228).
    """
    row = await _fetch_one(
        "SELECT story_kit, studio_project_id, brand_profile_id, status FROM generations WHERE id = ? AND user_id = ?",
        (generation_id, user_id),
    )
    if not row:
        raise HTTPException(status_code=404, detail="Generation not found")
    if str(row.get("status") or "") not in ("completed", "archived"):
        raise HTTPException(
            status_code=409, detail="Only finished renders can regenerate their story kit."
        )
    project, profile = await _load_story_kit_materials(row, user_id)
    if not project or not profile:
        raise HTTPException(
            status_code=409,
            detail="This render is not a story — it carries a post kit, not a story kit.",
        )
    try:
        kit = await _log_model_call(
            "story_kit", "text", TEXT_MODEL,
            lambda: ai_service.generate_story_kit(project, profile, row),
            user_id,
            brand_profile_id=row.get("brand_profile_id"),
            studio_project_id=row.get("studio_project_id"),
            generation_id=generation_id,
        )
    except Exception as e:
        raise HTTPException(status_code=502, detail=f"Could not regenerate the story kit: {str(e)[:800]}")
    if not isinstance(kit, dict):
        raise HTTPException(status_code=502, detail="Could not regenerate the story kit: empty response.")
    await _execute(
        "UPDATE generations SET story_kit = ?, updated_at = ? WHERE id = ?",
        (json.dumps(kit), now_iso(), generation_id),
    )
    return {"story_kit": kit}


