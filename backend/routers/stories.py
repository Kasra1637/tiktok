"""Stories: one router owns the story project, its plan, its render
submit, and its kit.

A story is a studio project row (kind='story', ADR 0227) whose renders
are ordinary generations, so this router is deliberately thin: project
creation writes the same table the wizard writes, the plan is one
ai_service call, the render submits through the composition root's
`_submit_generation` — the only render path — and the story kit is the
post kit's sibling, written at completion and regenerated by click.

The DB-touching and render helpers stay owned by the composition root
(server.py) and are injected via `configure_stories` at include time,
resolved at CALL time through `_cfg` — the same pattern routers/studio.py
uses, so a test that patches `server.<name>` intercepts the call here
too. Stateless deps (auth, models, ai_service, story_types) import
directly. No import of server here: an unconfigured call fails loudly
instead of half-working.
"""

import json
import logging
import uuid
from typing import Optional

from fastapi import APIRouter, BackgroundTasks, Depends, HTTPException, Request

import ai_service
import story_types
import video_providers
from ai_service import TEXT_MODEL
from auth import get_current_user_id
from models import (
    CreateStoryProjectRequest,
    GenerateStoryPlanRequest,
    GenerateStoryRequest,
    SuggestStoryScreenTextRequest,
    now_iso,
)

logger = logging.getLogger(__name__)

router = APIRouter()

_server = None


def configure_stories(server_module):
    """Inject the composition root. Called once at include time."""
    global _server
    _server = server_module


def _cfg(name):
    if _server is None:
        raise RuntimeError("stories router used before configure_stories ran")
    return getattr(_server, name)


def _fetch_one(*a, **k):
    return _cfg("_fetch_one")(*a, **k)


def _fetch_all(*a, **k):
    return _cfg("_fetch_all")(*a, **k)


def _execute(*a, **k):
    return _cfg("_execute")(*a, **k)


def _log_model_call(*a, **k):
    return _cfg("_log_model_call")(*a, **k)


def _submit_generation(*a, **k):
    return _cfg("_submit_generation")(*a, **k)


def _public_generation(*a, **k):
    return _cfg("_public_generation")(*a, **k)


def _public_project(*a, **k):
    return _cfg("_public_project")(*a, **k)


def _project_strategy(*a, **k):
    return _cfg("_project_strategy")(*a, **k)


def _require_profile_for_studio(*a, **k):
    return _cfg("_require_profile_for_studio")(*a, **k)


def _request_id(*a, **k):
    return _cfg("_request_id")(*a, **k)


def require_ai_configured(*a, **k):
    return _cfg("require_ai_configured")(*a, **k)


def _refuse_retired_project_assets(*a, **k):
    return _cfg("_refuse_retired_project_assets")(*a, **k)


